-- ---------------------------------------------------------------------------
-- Helper functions (SECURITY DEFINER so RLS policies can read roles without
-- recursing on the profiles policies themselves)
-- ---------------------------------------------------------------------------

create or replace function public.current_app_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role from public.profiles where id = auth.uid()
$$;

create or replace function public.is_staff()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.current_app_role() in ('checker', 'admin', 'owner')
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.current_app_role() in ('admin', 'owner')
$$;

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- Profile creation / sync from Discord sign-ins
-- ---------------------------------------------------------------------------

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  discord_id text;
  username text;
  display_name text;
  avatar_url text;
  cfg_owner text;
  cfg_locked boolean;
begin
  -- The numeric Discord user id lives on the auth identity row (provider_id)
  -- and is mirrored in metadata; try every known location.
  select coalesce(i.provider_id, i.identity_data->>'sub', i.identity_data->>'id')
  into discord_id
  from auth.identities i
  where i.user_id = new.id and i.provider = 'discord'
  limit 1;

  discord_id := coalesce(discord_id, new.raw_user_meta_data->>'sub',
                         new.raw_user_meta_data->>'id',
                         new.raw_user_meta_data->>'provider_id');
  if discord_id is null or discord_id = '' then
    discord_id := 'unknown-' || new.id::text;  -- should never happen for Discord
  end if;

  username      := coalesce(new.raw_user_meta_data->>'user_name',
                            new.raw_user_meta_data->>'preferred_username',
                            new.raw_user_meta_data->>'username');
  display_name  := coalesce(new.raw_user_meta_data->>'full_name',
                            new.raw_user_meta_data->>'name',
                            username,
                            'Member');
  avatar_url    := coalesce(new.raw_user_meta_data->>'avatar_url',
                            new.raw_user_meta_data->>'picture');

  insert into public.profiles (id, discord_id, username, display_name, avatar_url, role)
  values (new.id, discord_id, username, display_name, avatar_url, 'member')
  on conflict (id) do nothing;

  -- Owner bootstrap: the account whose discord id matches the configured
  -- owner id becomes the first owner, exactly once, until an owner exists.
  select value::text into cfg_owner from public.app_config where key = 'owner_discord_id';
  select coalesce(value::boolean, false) into cfg_locked from public.app_config where key = 'owner_bootstrap_locked';
  if cfg_owner is not null and cfg_owner <> '""' and cfg_owner <> ''
     and cfg_locked = false
     and not exists (select 1 from public.profiles where role = 'owner') then
    update public.profiles set role = 'owner', updated_at = now()
    where discord_id = cfg_owner;
  end if;

  return new;
end;
$$;

-- Keep username/display name/avatar in sync when the user signs in again and
-- Discord data has changed (metadata updates fire an UPDATE on auth.users).
create or replace function public.sync_profile_from_metadata()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.profiles set
    username     = coalesce(new.raw_user_meta_data->>'user_name',
                            new.raw_user_meta_data->>'preferred_username',
                            new.raw_user_meta_data->>'username',
                            profiles.username),
    display_name = coalesce(new.raw_user_meta_data->>'full_name',
                            new.raw_user_meta_data->>'name',
                            profiles.display_name),
    avatar_url   = coalesce(new.raw_user_meta_data->>'avatar_url',
                            new.raw_user_meta_data->>'picture',
                            profiles.avatar_url),
    updated_at   = now()
  where profiles.id = new.id;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create trigger on_auth_user_updated
  after update on auth.users
  for each row execute function public.sync_profile_from_metadata();

-- ---------------------------------------------------------------------------
-- Guards: roles and moderation fields can only change through the service
-- role (Edge Functions), never from a browser session.
-- ---------------------------------------------------------------------------

create or replace function public.protect_profile_privileged_fields()
returns trigger
language plpgsql
as $$
begin
  if auth.uid() is not null then
    if new.role is distinct from old.role then
      raise exception 'Roles can only be changed by authorised staff through the backend.';
    end if;
    if new.discord_id is distinct from old.discord_id then
      raise exception 'discord_id is immutable.';
    end if;
  end if;
  return new;
end;
$$;

create trigger profiles_protect_privileged_fields
  before update on public.profiles
  for each row execute function public.protect_profile_privileged_fields();

-- Contributions are written exclusively by Edge Functions (service role).
create or replace function public.protect_contribution_writes()
returns trigger
language plpgsql
as $$
begin
  if auth.uid() is not null then
    raise exception 'Contributions can only be modified through the backend.';
  end if;
  return new;
end;
$$;

create trigger contributions_protect_writes
  before update or delete on public.contributions
  for each row execute function public.protect_contribution_writes();

-- Audit log is strictly append-only for everyone.
create or replace function public.audit_logs_append_only()
returns trigger
language plpgsql
as $$
begin
  raise exception 'audit_logs is append-only; % is not permitted.', TG_OP;
end;
$$;

create trigger audit_logs_no_update
  before update or delete on public.audit_logs
  for each row execute function public.audit_logs_append_only();

create trigger contributions_touch_updated_at
  before update on public.contributions
  for each row execute function public.touch_updated_at();

create trigger profiles_touch_updated_at
  before update on public.profiles
  for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------------

alter table public.profiles                  enable row level security;
alter table public.contributions             enable row level security;
alter table public.contribution_status_history enable row level security;
alter table public.audit_logs                enable row level security;
alter table public.notification_outbox       enable row level security;
alter table public.app_config                enable row level security;

-- profiles: everyone sees their own row; staff can see all profiles (needed
-- to display contributor names in the review panel).
create policy "profiles: read own or staff"
  on public.profiles for select
  using (id = auth.uid() or public.is_staff());

-- users may never update their profile through the client API (Discord data
-- is synced server-side); no update policy on purpose. No insert/delete
-- policies either: rows are created/deleted by triggers and the service role.

-- contributions: members read their own; staff read everything. All writes
-- happen with the service role through Edge Functions only.
create policy "contributions: read own or staff"
  on public.contributions for select
  using (contributor_id = auth.uid() or public.is_staff());

create policy "status history: read own or staff"
  on public.contribution_status_history for select
  using (
    public.is_staff()
    or exists (
      select 1 from public.contributions c
      where c.id = contribution_id and c.contributor_id = auth.uid()
    )
  );

create policy "audit logs: staff read only"
  on public.audit_logs for select
  using (public.is_staff());

-- notification_outbox: no policies at all — service role only.

-- app_config: authenticated users may read the public limits (the UI shows
-- "you can submit again in N minutes"); only the service role writes.
create policy "app_config: authenticated read"
  on public.app_config for select
  using (auth.role() = 'authenticated');

-- Defense in depth: strip write privileges from the client-facing roles even
-- though RLS already denies them (RLS with no policy = no access).
revoke insert, update, delete on public.contributions              from anon, authenticated;
revoke insert, update, delete on public.contribution_status_history from anon, authenticated;
revoke all                                                          on public.notification_outbox from anon, authenticated;
revoke insert, update, delete on public.audit_logs                 from anon, authenticated;
revoke insert, update, delete on public.app_config                 from anon, authenticated;
revoke insert, update, delete on public.profiles                   from anon, authenticated;

-- ---------------------------------------------------------------------------
-- Public views (no authentication): statistics and the accepted-contribution
-- log. They run as the view owner and expose ONLY safe, aggregated or
-- accepted data — never declined, deleted or private information.
-- ---------------------------------------------------------------------------

create view public.public_stats
with (security_invoker = false)
as
  select
    (select count(*) from public.contributions)                        as contributions_submitted,
    (select count(*) from public.contributions where status='accepted') as contributions_accepted,
    (select count(*) from public.contributions where status='declined') as contributions_declined,
    (select count(*) from public.contributions where status='pending')  as contributions_pending,
    -- "contributor" = an account with at least one accepted contribution.
    (select count(distinct contributor_id) from public.contributions
       where status='accepted')                                         as contributors;

grant select on public.public_stats to anon, authenticated;

create view public.public_log
with (security_invoker = false)
as
  select c.number,
         c.title,
         c.type,
         c.entry_id,
         c.entry_series,
         p.display_name as contributor_name,
         c.reviewed_at  as accepted_at
  from public.contributions c
  join public.profiles p on p.id = c.contributor_id
  where c.status = 'accepted';

grant select on public.public_log to anon, authenticated;

