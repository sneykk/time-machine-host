-- ============================================================================
-- Time Machine — backend schema (Supabase / Postgres)
-- Run from a fresh Supabase project: Dashboard → SQL Editor → paste → Run.
--
-- Design notes
--   * Archive JSON files in GitHub remain the single source of truth for
--     archive CONTENT. This database stores accounts, roles, contributions,
--     moderation history and audit logs.
--   * All client-facing writes go through Edge Functions using the service
--     role key; RLS below denies direct writes from browsers so the
--     server-side validation, rate limits and audit events cannot be skipped.
--   * audit_logs is append-only: a trigger rejects UPDATE/DELETE for anyone,
--     including the service role. Nothing in the application ever mutates it.
-- ============================================================================

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create sequence public.contribution_number_seq start 1;

create table public.profiles (
  id           uuid primary key references auth.users (id) on delete cascade,
  discord_id   text not null unique,
  username     text,
  display_name text not null default 'Member',
  avatar_url   text,
  -- 'owner' / 'admin' / 'checker' / 'member'; guests have no profile row.
  role         text not null default 'member'
    check (role in ('member', 'checker', 'admin', 'owner')),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create table public.contributions (
  id             uuid primary key default gen_random_uuid(),
  number         bigint not null unique default nextval('public.contribution_number_seq'),
  contributor_id uuid not null references public.profiles (id) on delete restrict,
  type           text not null check (char_length(type) <= 40),
  title          text not null check (char_length(title) between 1 and 200),
  entry_id       text check (entry_id is null or entry_id ~ '^[a-z0-9-]{1,60}$'),
  entry_series   text check (entry_series is null or entry_series ~ '^[a-z0-9-]{1,40}$'),
  -- Answers exactly as the contributor submitted them.
  payload        jsonb not null default '{}'::jsonb,
  -- True when a checker edited the submission during review; the edited
  -- version is kept here so the original is never lost.
  payload_edited jsonb,
  -- Normalized archive patch built by the review UI and applied on accept.
  proposed_patch jsonb,
  status         text not null default 'pending'
    check (status in ('pending', 'accepted', 'declined', 'deleted')),
  reviewer_id    uuid references public.profiles (id),
  reviewed_at    timestamptz,
  review_reason  text check (review_reason is null or char_length(review_reason) <= 2000),
  -- Archive sync outcome. 'not_required' = never touched the archive
  -- (pending/declined/deleted), 'committed' = GitHub commit succeeded,
  -- 'failed' = commit attempted and failed (retryable), 'recovered' =
  -- commit succeeded on a later retry.
  commit_sha     text,
  sync_state     text not null default 'not_required'
    check (sync_state in ('not_required', 'committed', 'failed', 'recovered')),
  sync_error     text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create index contributions_contributor_idx on public.contributions (contributor_id, created_at desc);
create index contributions_status_idx on public.contributions (status, created_at desc);
create index contributions_entry_idx on public.contributions (entry_id);

create table public.contribution_status_history (
  id              bigint generated always as identity primary key,
  contribution_id uuid not null references public.contributions (id) on delete restrict,
  from_status     text,
  to_status       text not null,
  actor_id        uuid references public.profiles (id),
  reason          text,
  created_at      timestamptz not null default now()
);

create index status_history_contribution_idx on public.contribution_status_history (contribution_id, created_at);

create table public.audit_logs (
  id                  bigint generated always as identity primary key,
  contribution_id     uuid references public.contributions (id) on delete set null,
  contribution_number bigint,
  action              text not null,
  actor_id            uuid references public.profiles (id),
  actor_display_name  text,
  target_user_id      uuid references public.profiles (id),
  target_display_name text,
  entity_type         text,
  entity_id           text,
  -- [{ field, before, after }] generated by comparing real data, never from
  -- a human-written description.
  changes             jsonb not null default '[]'::jsonb,
  review_notes        text,
  commit_sha          text,
  created_at          timestamptz not null default now()
);

create index audit_logs_created_idx on public.audit_logs (created_at desc);
create index audit_logs_contribution_idx on public.audit_logs (contribution_id);
create index audit_logs_action_idx on public.audit_logs (action);

-- Discord webhook delivery state. event_key is unique, which makes retries
-- idempotent: one notification per event, ever.
create table public.notification_outbox (
  id         bigint generated always as identity primary key,
  event_key  text not null unique,
  event      text not null,
  payload    jsonb not null,
  status     text not null default 'pending' check (status in ('pending', 'sent', 'failed', 'skipped')),
  attempts   int  not null default 0,
  last_error text,
  created_at timestamptz not null default now(),
  sent_at    timestamptz
);

-- Server-side configuration: rate limits, owner bootstrap. Values are jsonb
-- so the shape can evolve without migrations.
create table public.app_config (
  key        text primary key,
  value      jsonb not null,
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles (id)
);

insert into public.app_config (key, value) values
